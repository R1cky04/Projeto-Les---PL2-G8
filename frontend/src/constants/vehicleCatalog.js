export function getCatalogBrands() {
  return VEHICLE_CATALOG.map((entry) => entry.brand)
}

export function getCatalogModels(brand) {
  const entry = VEHICLE_CATALOG.find((item) => item.brand === brand)
  return entry ? entry.models : []
}

export function getCatalogSubmodels(brand, model) {
  const key = `${brand}::${model}`
  return VEHICLE_SUBMODELS[key] || ['Standard']
}

export function getCatalogSummary(brand, model, submodel) {
  const parts = [brand, model, submodel].filter(Boolean)
  return parts.join(' • ')
}
